import { execFileSync } from 'node:child_process'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { CONTACTS, NOW_PLAYING_URL } from './content.ts'
import { fetchStats } from './github.ts'
import { buildSections, type Section, type ThemeName } from './sections.ts'

const ASSETS = 'assets'
const THEME_NAMES: readonly ThemeName[] = ['dark', 'light']

const assetPath = (section: Section, theme: ThemeName): string =>
  section.themed ? `${ASSETS}/${section.name}-${theme}.svg` : `${ASSETS}/${section.name}.svg`

const escapeAttr = (s: string): string =>
  s.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;')

function sectionMarkup(section: Section): string {
  const alt = escapeAttr(section.alt)
  const img = `<img src="${assetPath(section, 'dark')}" alt="${alt}" width="100%" />`
  const picture = section.themed
    ? `<picture><source media="(prefers-color-scheme: light)" srcset="${assetPath(section, 'light')}" />${img}</picture>`
    : img
  return section.href ? `<a href="${section.href}">${picture}</a>` : picture
}

function buildReadme(sections: readonly Section[]): string {
  const contacts = CONTACTS.map((c) => `[${c.label}](${c.href})`).join(' · ')
  const nowPlaying =
    `<a href="https://zaebal.dev"><picture>` +
    `<source media="(prefers-color-scheme: light)" srcset="${NOW_PLAYING_URL}?theme=light" />` +
    `<img src="${NOW_PLAYING_URL}" alt="What Sergei is listening to on Spotify" width="100%" />` +
    `</picture></a>`
  return [
    '<!-- Generated by src/build.ts. Edit src/content.ts instead. -->',
    '',
    `<p>\n${sections.map(sectionMarkup).join('\n')}\n</p>`,
    '',
    `<p>\n${nowPlaying}\n</p>`,
    '',
    contacts,
    '',
  ].join('\n')
}

async function main(): Promise<void> {
  const token = process.env.GITHUB_TOKEN ?? execFileSync('gh', ['auth', 'token'], { encoding: 'utf8' }).trim()
  const now = new Date()
  const stats = await fetchStats(token)
  const sections = buildSections(stats, now)

  const files = await Promise.all(
    sections.flatMap((section) =>
      (section.themed ? THEME_NAMES : (['dark'] as const)).map(async (theme) => ({
        path: assetPath(section, theme),
        svg: await section.render(theme).toSvg(),
      })),
    ),
  )

  await rm(ASSETS, { recursive: true, force: true })
  await mkdir(ASSETS, { recursive: true })
  await Promise.all(files.map(({ path, svg }) => writeFile(path, svg)))
  await writeFile('README.md', buildReadme(sections))
}

await main()
