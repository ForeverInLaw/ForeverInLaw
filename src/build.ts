import { execFileSync } from 'node:child_process'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { NOW_PLAYING_URL } from './content.ts'
import { fetchStats } from './github.ts'
import { buildSections, type Block, type Image } from './sections.ts'
import type { LayoutName, ThemeName } from './theme.ts'

const ASSETS = 'assets'
const THEME_NAMES: readonly ThemeName[] = ['dark', 'light']
const LAYOUT_NAMES: readonly LayoutName[] = ['wide', 'narrow']
/** Below this viewport width the narrow layout is served; GitHub's README column is then under ~560px. */
const NARROW = '(max-width: 600px)'
const LIGHT = '(prefers-color-scheme: light)'

const slicePath = (image: Image, layout: LayoutName, theme: ThemeName): string => `${ASSETS}/${image.name}-${layout}-${theme}.svg`
const inlinePath = (image: Image, theme: ThemeName): string => `${ASSETS}/${image.name}-${theme}.svg`

const escapeAttr = (s: string): string =>
  s.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;')

const source = (media: string, srcset: string): string => `<source media="${media}" srcset="${srcset}" />`
const linked = (image: Image, inner: string): string => (image.href ? `<a href="${image.href}">${inner}</a>` : inner)

/** Narrow before wide and light before dark, because <picture> takes the first matching source. */
function sliceMarkup(image: Image): string {
  const sources = [
    source(`${NARROW} and ${LIGHT}`, slicePath(image, 'narrow', 'light')),
    source(NARROW, slicePath(image, 'narrow', 'dark')),
    source(LIGHT, slicePath(image, 'wide', 'light')),
  ].join('')
  const img = `<img src="${slicePath(image, 'wide', 'dark')}" alt="${escapeAttr(image.alt)}" width="100%" />`
  return linked(image, `<picture>${sources}${img}</picture>`)
}

function inlineMarkup(image: Image, height: number): string {
  const img = `<img src="${inlinePath(image, 'dark')}" alt="${escapeAttr(image.alt)}" height="${height}" />`
  return linked(image, `<picture>${source(LIGHT, inlinePath(image, 'light'))}${img}</picture>`)
}

/** Consecutive slices stack in one paragraph; each inline group gets its own, so chips sit in a row. */
function paragraphs(blocks: readonly Block[]): string[][] {
  const groups: string[][] = []
  for (const block of blocks) {
    const previous = groups.at(-1)
    if (block.kind === 'inline') groups.push(block.images.map((image) => inlineMarkup(image, block.height)), [])
    else if (previous) previous.push(sliceMarkup(block.image))
    else groups.push([sliceMarkup(block.image)])
  }
  return groups.filter((group) => group.length > 0)
}

function buildReadme(blocks: readonly Block[]): string {
  const card = (theme: ThemeName, layout: LayoutName) => `${NOW_PLAYING_URL}?theme=${theme}&amp;layout=${layout}`
  const nowPlaying =
    `<a href="https://zaebal.dev"><picture>` +
    source(`${NARROW} and ${LIGHT}`, card('light', 'narrow')) +
    source(NARROW, card('dark', 'narrow')) +
    source(LIGHT, card('light', 'wide')) +
    `<img src="${card('dark', 'wide')}" alt="What Sergei is listening to on Spotify" width="100%" />` +
    `</picture></a>`
  // The card closes the last stack of slices rather than opening a paragraph, which would add a margin.
  const groups = paragraphs(blocks)
  groups.at(-1)?.push(nowPlaying)
  const body = groups.map((lines) => `<p>\n${lines.join('\n')}\n</p>`)
  return ['<!-- Generated by src/build.ts. Edit src/content.ts instead. -->', '', ...body.flatMap((p) => [p, '']), ''].join('\n')
}

/** Every file a block ships, paired with its renderer. */
function assetJobs(block: Block): { path: string; render: () => ReturnType<Image['render']> }[] {
  if (block.kind === 'inline') {
    return block.images.flatMap((image) =>
      THEME_NAMES.map((theme) => ({ path: inlinePath(image, theme), render: () => image.render(theme, 'wide') })),
    )
  }
  const { image } = block
  return LAYOUT_NAMES.flatMap((layout) =>
    THEME_NAMES.map((theme) => ({ path: slicePath(image, layout, theme), render: () => image.render(theme, layout) })),
  )
}

async function main(): Promise<void> {
  const token = process.env.GITHUB_TOKEN ?? execFileSync('gh', ['auth', 'token'], { encoding: 'utf8' }).trim()
  const blocks = buildSections(await fetchStats(token))
  const files = await Promise.all(
    blocks.flatMap(assetJobs).map(async ({ path, render }) => ({ path, svg: await render().toSvg() })),
  )

  await rm(ASSETS, { recursive: true, force: true })
  await mkdir(ASSETS, { recursive: true })
  await Promise.all(files.map(({ path, svg }) => writeFile(path, svg)))
  await writeFile('README.md', buildReadme(blocks))
}

await main()
